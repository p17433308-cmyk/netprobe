"""Generate CVE-ready vulnerability reports."""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path


CVE_TEMPLATE = """
## Vulnerability Report

**Date:** {date}
**Reporter:** DFIR Research Lab
**Tool:** NetProbe v1.0.0

---

### Summary

{summary}

### Affected Software

- **Product:** {product}
- **Vendor:** {vendor}
- **Affected Versions:** {affected_versions}
- **Fixed Version:** [pending vendor response]

### Vulnerability Details

- **Type:** {vuln_type}
- **CWE:** {cwe} — {cwe_name}
- **CVSS v3.1 Estimate:** {cvss}/10.0
- **Attack Vector:** Network
- **Attack Complexity:** Low
- **Privileges Required:** None
- **User Interaction:** {user_interaction}

### Description

{description}

### Impact

{impact}

### Proof of Concept

A crafted {artifact_type} file triggers the vulnerability when processed by {product}.

**Steps to reproduce:**
1. Build {product} with AddressSanitizer enabled
2. Run: `{reproduce_cmd}`
3. Observe the crash with ASAN output showing {crash_type}

**Crash output (abbreviated):**
```
{crash_output}
```

### Root Cause

{root_cause}

### Suggested Fix

{suggested_fix}

### Timeline

- {date}: Vulnerability discovered by NetProbe fuzzing campaign
- {date}: Report sent to {vendor_email}
- [pending]: Vendor acknowledgment
- [pending]: Patch released
- [pending]: CVE assigned

### References

- NetProbe: https://github.com/[repo]/netprobe
- {product} security page: {security_page}

---
*This report was generated by NetProbe — Who Watches the Watchmen?*
"""


class CVEReportGenerator:
    PRODUCT_INFO = {
        "wireshark": {
            "product": "Wireshark",
            "vendor": "Wireshark Foundation",
            "vendor_email": "security@wireshark.org",
            "security_page": "https://www.wireshark.org/security/",
            "reproduce_cmd": "tshark -r {pcap_file} -V",
            "user_interaction": "Required (open pcap / capture traffic)",
        },
        "suricata": {
            "product": "Suricata",
            "vendor": "Open Information Security Foundation",
            "vendor_email": "security@openinfosecfoundation.org",
            "security_page": "https://suricata.io/security/",
            "reproduce_cmd": "suricata -r {pcap_file}",
            "user_interaction": "None (passive monitoring)",
        },
        "tcpdump": {
            "product": "tcpdump",
            "vendor": "The Tcpdump Group",
            "vendor_email": "security@tcpdump.org",
            "security_page": "https://www.tcpdump.org/security.html",
            "reproduce_cmd": "tcpdump -r {pcap_file} -vvv",
            "user_interaction": "None (passive monitoring)",
        },
    }

    def generate(self, crash_id: str, crash_dir: Path, target: str = "wireshark") -> str:
        """Generate a CVE report from a crash."""
        report_file = crash_dir / "campaign_report.json"
        crash = None

        if report_file.exists():
            data = json.loads(report_file.read_text())
            for c in data.get("unique_crashes", []):
                if str(c.get("crash_id", "")).startswith(crash_id):
                    crash = c
                    break

        if not crash:
            return f"Crash {crash_id} not found in {crash_dir}"

        info = self.PRODUCT_INFO.get(target, self.PRODUCT_INFO["wireshark"])

        return CVE_TEMPLATE.format(
            date=date.today().isoformat(),
            summary=f"A {crash.get('crash_type', 'vulnerability')} in {info['product']} "
                    f"allows denial of service{' and potentially remote code execution' if crash.get('rce_potential') else ''} "
                    f"via a crafted pcap file.",
            product=info["product"],
            vendor=info["vendor"],
            affected_versions="[to be determined]",
            vuln_type=crash.get("crash_type", "unknown"),
            cwe=crash.get("cwe", "CWE-unknown"),
            cwe_name=crash.get("cwe_name", "Unknown"),
            cvss=crash.get("cvss_estimate", 5.0),
            user_interaction=info["user_interaction"],
            description=f"A {crash.get('cwe_name', 'vulnerability')} exists in {info['product']} "
                       f"that can be triggered by processing a specially crafted packet capture file. "
                       f"The vulnerability occurs in the function {crash.get('function', '[unknown]')}.",
            impact=f"An attacker can cause {info['product']} to crash (denial of service) "
                  f"by sending crafted network traffic or providing a malicious pcap file. "
                  + ("This may also allow remote code execution. " if crash.get("rce_potential") else "")
                  + f"This affects any environment where {info['product']} processes untrusted network data.",
            artifact_type="pcap",
            reproduce_cmd=info["reproduce_cmd"].format(pcap_file=crash.get("filename", "crash.pcap")),
            crash_type=crash.get("crash_type", "crash"),
            crash_output=crash.get("asan_report", crash.get("stderr_snippet", ""))[:500],
            root_cause=f"The crash occurs in {crash.get('function', '[unknown]')} due to "
                      f"{crash.get('cwe_name', 'a vulnerability')}. "
                      f"The function does not properly validate input from the packet data "
                      f"before using it in a memory operation.",
            suggested_fix="Add proper bounds checking for packet-derived values before use "
                         "in memory operations. Validate that length fields do not exceed "
                         "the remaining packet data.",
            vendor_email=info["vendor_email"],
            security_page=info["security_page"],
        )


class MarkdownReportGenerator:
    def generate(self, crash_id: str, crash_dir: Path, target: str = "wireshark") -> str:
        gen = CVEReportGenerator()
        return gen.generate(crash_id, crash_dir, target)
