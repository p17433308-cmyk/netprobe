"""Generate weaponized pcaps and PoC packages from crash findings.

For authorized security research and responsible disclosure only.
"""

from __future__ import annotations

import json
import shutil
import struct
from datetime import date
from pathlib import Path

from rich.console import Console


class WeaponizedPcapGenerator:
    """Take a crash-triggering pcap and produce a clean, minimal, weaponized version."""

    def minimize(self, pcap_path: Path, binary_path: Path | None = None,
                 max_iterations: int = 100) -> Path:
        """Delta-debug minimize a crash pcap to smallest trigger."""
        data = pcap_path.read_bytes()

        if len(data) <= 40:
            return pcap_path

        header = data[:24]
        packets_data = data[24:]

        if not binary_path:
            minimized_path = pcap_path.parent / f"min_{pcap_path.name}"
            minimized_path.write_bytes(data)
            return minimized_path

        from netprobe.harness.wireshark import WiresharkHarness
        harness = WiresharkHarness(binary_path=binary_path, timeout=10.0)

        current = bytearray(data)
        current_size = len(current)

        for iteration in range(max_iterations):
            if len(current) <= 40:
                break

            chunk_size = max(1, (len(current) - 24) // 4)
            reduced = False

            for offset in range(24, len(current) - chunk_size, chunk_size):
                candidate = bytearray(current[:offset] + current[offset + chunk_size:])
                if len(candidate) < 24:
                    continue

                tmp = pcap_path.parent / f"minimize_tmp.pcap"
                tmp.write_bytes(bytes(candidate))
                result = harness.execute(tmp)
                tmp.unlink(missing_ok=True)

                if result.crashed:
                    current = candidate
                    reduced = True
                    break

            if not reduced:
                if chunk_size <= 1:
                    break

        minimized_path = pcap_path.parent / f"min_{pcap_path.name}"
        minimized_path.write_bytes(bytes(current))
        return minimized_path

    def stabilize(self, pcap_path: Path, binary_path: Path,
                  attempts: int = 10) -> tuple[bool, float]:
        """Verify crash is reliable — return (stable, repro_rate)."""
        from netprobe.harness.wireshark import WiresharkHarness
        harness = WiresharkHarness(binary_path=binary_path, timeout=10.0)

        crashes = 0
        for _ in range(attempts):
            result = harness.execute(pcap_path)
            if result.crashed:
                crashes += 1

        rate = crashes / attempts
        return rate >= 0.9, rate

    def package(self, pcap_path: Path, crash_info: dict,
                output_dir: Path, target: str = "wireshark") -> Path:
        """Bundle everything into a disclosure-ready package."""
        pkg_dir = output_dir / f"CVE_PoC_{crash_info.get('crash_id', 'unknown')}"
        pkg_dir.mkdir(parents=True, exist_ok=True)

        shutil.copy2(pcap_path, pkg_dir / "crash.pcap")

        reproduce_sh = f"""#!/bin/bash
# Reproduction script for {crash_info.get('cwe', 'vulnerability')}
# Target: {target}
# Crash type: {crash_info.get('crash_type', 'unknown')}
# Function: {crash_info.get('function', 'unknown')}

echo "=== Reproducing {crash_info.get('cwe', 'vulnerability')} ==="
echo "Running tshark with ASAN..."

export ASAN_OPTIONS="detect_leaks=0:abort_on_error=1:symbolize=1"
tshark -r crash.pcap -V 2>&1

echo ""
echo "Exit code: $?"
echo "If tshark crashed, the vulnerability is confirmed."
"""
        (pkg_dir / "reproduce.sh").write_text(reproduce_sh)
        (pkg_dir / "reproduce.sh").chmod(0o755)

        dockerfile = f"""FROM ubuntu:22.04
RUN apt-get update && apt-get install -y tshark
COPY crash.pcap /crash.pcap
COPY reproduce.sh /reproduce.sh
RUN chmod +x /reproduce.sh
CMD ["/reproduce.sh"]
"""
        (pkg_dir / "Dockerfile").write_text(dockerfile)

        metadata = {
            "date": date.today().isoformat(),
            "tool": "NetProbe v1.0.0",
            "target": target,
            "crash_info": crash_info,
            "pcap_file": "crash.pcap",
            "repro_script": "reproduce.sh",
        }
        (pkg_dir / "metadata.json").write_text(json.dumps(metadata, indent=2, default=str))

        readme = f"""# Vulnerability PoC — {crash_info.get('cwe', 'Unknown')}

**Generated by:** NetProbe — Who Watches the Watchmen?
**Date:** {date.today().isoformat()}
**Target:** {target}

## Quick Reproduction

```bash
./reproduce.sh
```

Or with Docker:
```bash
docker build -t cve-poc .
docker run cve-poc
```

## Details

- **CWE:** {crash_info.get('cwe', 'Unknown')} — {crash_info.get('cwe_name', 'Unknown')}
- **Crash Type:** {crash_info.get('crash_type', 'Unknown')}
- **Function:** {crash_info.get('function', 'Unknown')}
- **Severity:** {crash_info.get('severity', 'Unknown')}
- **CVSS Estimate:** {crash_info.get('cvss_estimate', 'N/A')}
- **RCE Potential:** {'Yes' if crash_info.get('rce_potential') else 'No'}
"""
        (pkg_dir / "README.md").write_text(readme)

        return pkg_dir
